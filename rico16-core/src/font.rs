//! The built-in 8x8 font. SPEC §6.5.
//!
//! Glyph data is `font8x8_basic` by Daniel Hepper, public domain, itself based on
//! the IBM VGA 8x8 font. Each glyph is eight rows of eight pixels; bit 0 is the
//! leftmost pixel. Only printable ASCII 32-126 is stored: everything else draws
//! [`PLACEHOLDER`], so no string can make text rendering fail.

/// First code point with a real glyph, space.
pub const FIRST_PRINTABLE: u32 = 32;

/// Last code point with a real glyph, tilde.
pub const LAST_PRINTABLE: u32 = 126;

/// Advance per glyph, in pixels. SPEC §6.5.
pub const GLYPH_WIDTH: i32 = 8;

/// Glyph height, in pixels. SPEC §6.5.
pub const GLYPH_HEIGHT: i32 = 8;

