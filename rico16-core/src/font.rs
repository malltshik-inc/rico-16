/// Drawn for code points the font does not cover. SPEC §6.5.
pub const PLACEHOLDER: [u8; 8] = [0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00];

/// The bitmap for one character. SPEC §6.5.
pub fn glyph(character: char) -> &'static [u8; 8] {
    let code = character as u32;
    if (FIRST_PRINTABLE..=LAST_PRINTABLE).contains(&code) {
        &GLYPHS[(code - FIRST_PRINTABLE) as usize]
    } else {
        &PLACEHOLDER
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_covers_printable_ascii_exactly_once() {
        assert_eq!(
            GLYPHS.len(),
            (LAST_PRINTABLE - FIRST_PRINTABLE + 1) as usize
        );
        for code in FIRST_PRINTABLE..=LAST_PRINTABLE {
            let bitmap = glyph(char::from_u32(code).unwrap());
            assert!(
                code == 32 || bitmap.iter().any(|row| *row != 0),
                "U+{code:04X} is blank"
            );
        }
    }

    #[test]
    fn uppercase_a_starts_with_the_expected_bits() {
        // Pinned so an accidental shift of the table is caught. SPEC §6.5.
        assert_eq!(
            glyph('A'),
            &[0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]
        );
    }

    #[test]
    fn non_ascii_falls_back_to_the_placeholder() {
        assert_eq!(glyph('Ω'), &PLACEHOLDER);
        assert_eq!(glyph('😀'), &PLACEHOLDER);
    }
}
